import assert from "node:assert/strict";
import fs from "node:fs";
const src=fs.readFileSync("help-owner.js","utf8").replace(/^import .*$/gm,"");
const mod=await import("data:text/javascript;base64,"+Buffer.from(src+"\nconst initFirebase=0,getFirebaseUser=0,listCloudUsers=0,mountSixDigitPinInput=0;").toString("base64"));
const {encodeHelpCard,parseHelpCard,renderHelpCardBubble,helpCardLines,mapLink,HELP_PICTURE_MESSAGES}=mod;
const t=encodeHelpCard({alertId:"a1",kind:"alert",location:{lat:43.65,lng:-79.38,acc:12.7},wifi:"HomeNet"});
const c=parseHelpCard(t);
assert.equal(c.alertId,"a1");assert.equal(c.location.acc,13);assert.equal(c.wifi,"HomeNet");
assert.equal(parseHelpCard('{"fidunioAttachment":1}'),null);
assert.equal(parseHelpCard("hello"),null);
assert.equal(parseHelpCard('{"fidunioHelp":1,"alertId":"a","kind":"evil"}'),null);
assert.equal(encodeHelpCard({alertId:"a",kind:"note",note:"x".repeat(300)}).length<200,true,"note capped at 100");
assert.match(renderHelpCardBubble({...c,wifi:'<img src=x onerror=1>'}),/&lt;img/);
assert.match(mapLink(c.location),/^https:\/\/maps\.google\.com\/\?q=43\.650000,-79\.380000$/);
assert.deepEqual(helpCardLines({kind:"alert",test:true}),["TEST — 🆘 HELP alert"]);
assert.deepEqual(HELP_PICTURE_MESSAGES.map(p=>p.text),["I'm lost","I'm hurt","I'm scared","Come now"]);
const app=fs.readFileSync("app.js","utf8");
assert.match(app,/async function signOutWithNotificationCleanup\(\)\{if\(!\(await helpOwner\.allowSignOut\(\)\)\)/,"protected account: Sign Out needs the PIN");
assert.match(app,/help:\(\)=>helpOwner\.renderHelp\(\)/);
console.log("HELP app gate passed");
