import assert from "node:assert/strict";
import fs from "node:fs";
/* KISS HELP (2026-11-25): card format, names, no Wi-Fi, no pictures, no account protection. */
const src=fs.readFileSync("help-owner.js","utf8").replace(/^import .*$/gm,"");
const mod=await import("data:text/javascript;base64,"+Buffer.from(src+"\nconst initFirebase=0,listCloudUsers=0,prepareUrgentAlerts=0,currentLocation=0;").toString("base64"));
const {encodeHelpCard,parseHelpCard,renderHelpCardBubble,helpCardLines,mapLink,joinNames,HELP_GROUP_PREFIX}=mod;
const t=encodeHelpCard({alertId:"a1",kind:"alert",location:{lat:43.65,lng:-79.38,acc:12.7},wifi:"HomeNet"});
const c=parseHelpCard(t);
assert.equal(c.alertId,"a1");assert.equal(c.location.acc,13);assert.equal(c.wifi,undefined,"no Wi-Fi name is sent");
assert.equal(parseHelpCard('{"fidunioAttachment":1}'),null);
assert.equal(parseHelpCard("hello"),null);
assert.equal(parseHelpCard('{"fidunioHelp":1,"alertId":"a","kind":"evil"}'),null);
assert.ok(parseHelpCard(encodeHelpCard({alertId:"a",kind:"coming"})),"'I'm coming' card");
assert.match(renderHelpCardBubble({kind:"note",alertId:"a",note:'<img src=x onerror=1>'}),/&lt;img/);
assert.match(mapLink(c.location),/^https:\/\/maps\.google\.com\/\?q=43\.650000,-79\.380000$/);
assert.deepEqual(helpCardLines({kind:"alert"}),["HELP"]);
assert.deepEqual(helpCardLines({kind:"safe"}),["I'm OK now"]);
assert.match(renderHelpCardBubble(c),/Open in Maps/);
assert.equal(joinNames(["Willy Rosales","Joseph Rosales"]),"Willy Rosales and Joseph Rosales");
assert.equal(joinNames(["A","B","C"]),"A, B and C");
assert.equal(HELP_GROUP_PREFIX,"HELP — ");
const owner=fs.readFileSync("help-owner.js","utf8");
assert.ok(!/Protect this account|Test my HELP|I'm lost|FidunioWifi|Capacitor/.test(owner),"KISS: no protection, test button, pictures, Wi-Fi or device calls in the shared HELP module");
assert.match(owner,/id="helpChoose">Choose HELP contacts</,"contacts list stays collapsed until 'Choose HELP contacts'");
const app=fs.readFileSync("app.js","utf8");
assert.match(app,/help:\(\)=>helpOwner\.renderHelp\(\)/);
assert.match(app,/helpOwner\.afterUnlock\(\);/,"an unanswered HELP opens after unlock");
assert.match(owner,/String\(uid\)===st\.uid&&\(st\.unsub\.length\|\|st\.starting\)\)return;/,"a repeated sign-in event for the same person keeps the HELP contacts");
console.log("HELP app gate passed");
